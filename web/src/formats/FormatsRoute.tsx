import { useEffect, useState, type ReactNode } from "react";
import { formatsApi, type Format, type FormatSummary, type Rule } from "./api";
import { Preview } from "../Preview";
import { videoHref } from "../videos/routes";
import "./formats.css";

const ROOT = "#/formats";
const DOC = "#/doc/";

function useHash(): string {
  const [hash, setHash] = useState(window.location.hash);
  useEffect(() => {
    const onHash = () => setHash(window.location.hash);
    window.addEventListener("hashchange", onHash);
    return () => window.removeEventListener("hashchange", onHash);
  }, []);
  return hash;
}

function route(hash: string): { id: string | null } | null {
  if (hash === ROOT) {
    return { id: null };
  }
  return hash.startsWith(ROOT + "/") ? { id: decodeURIComponent(hash.slice(ROOT.length + 1)) } : null;
}

export function FormatsNav() {
  const active = route(useHash()) !== null;
  return (
    <section className="group">
      <h2>Shelves</h2>
      <ul>
        <li>
          <a href={ROOT} className={active ? "active" : ""}>
            <span className="name">Formats</span>
          </a>
        </li>
      </ul>
    </section>
  );
}

export function FormatsRoute({ fallback }: { fallback: ReactNode }) {
  const current = route(useHash());
  if (!current) {
    return <>{fallback}</>;
  }
  return (
    <main className="doc formats">
      {current.id ? <FormatPage key={current.id} id={current.id} /> : <FormatList />}
    </main>
  );
}

function FormatList() {
  const [formats, setFormats] = useState<FormatSummary[] | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    formatsApi.list().then(setFormats, (e: Error) => setError(e.message));
  }, []);

  if (error) {
    return <p className="error">{error}</p>;
  }
  if (!formats) {
    return <p className="muted">Loading…</p>;
  }
  return (
    <>
      <h1>Formats</h1>
      {formats.length === 0 ? (
        <p className="muted">
          No <code>formats/*/FORMAT.md</code> in this checkout.
        </p>
      ) : (
        <ul className="format-cards">
          {formats.map((f) => (
            <li key={f.id}>
              <a href={`${ROOT}/${encodeURIComponent(f.id)}`}>
                <strong>{f.title}</strong>
                <code className="path">{f.id}</code>
                <span className="muted">{f.has_hook_library ? "Hook library exported" : "no Hook library yet"}</span>
              </a>
            </li>
          ))}
        </ul>
      )}
    </>
  );
}

function FormatPage({ id }: { id: string }) {
  const [format, setFormat] = useState<Format | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    formatsApi.get(id).then(setFormat, (e: Error) => setError(e.message));
  }, [id]);

  if (error) {
    return <p className="error">{error}</p>;
  }
  if (!format) {
    return <p className="muted">Loading…</p>;
  }
  return (
    <>
      <p className="crumbs">
        <a href={ROOT}>Formats</a> / {format.id}
      </p>
      <div className="doc-head">
        <div>
          <h1>{format.title}</h1>
          <code className="path">{format.format.path}</code>
        </div>
        <a className="button" href={DOC + encodeURIComponent(format.format.path)}>
          Edit FORMAT.md
        </a>
      </div>

      <section className="format-section">
        <Preview text={format.format.text} kind="markdown" />
      </section>

      <section className="format-section">
        <h2>Hook library</h2>
        {format.hook_library ? (
          <>
            <p className="muted">
              <code>{format.hook_library.path}</code> · read-only, generated by <code>hooks export</code>
            </p>
            <Preview text={format.hook_library.text} kind="markdown" />
          </>
        ) : (
          <p className="muted">
            Not exported yet: <code>python -m cf.research hooks export {format.id}</code>
          </p>
        )}
      </section>

      <RulesSection format={format} />

      <section className="format-section">
        <h2>Videos ({format.videos.length})</h2>
        {format.videos.length === 0 ? (
          <p className="muted">
            No Video (<code>videos/*/video.json</code> or legacy Reel) with format <code>{format.id}</code> under the
            footage root.
          </p>
        ) : (
          <table className="grid">
            <thead>
              <tr>
                <th>Video</th>
                <th>Status</th>
                <th>Channel</th>
                <th>Folder</th>
              </tr>
            </thead>
            <tbody>
              {format.videos.map((v) => (
                <tr key={v.slug}>
                  <td>
                    <a href={videoHref(v.slug)}>{v.title}</a>
                  </td>
                  <td>{v.status ?? "—"}</td>
                  <td>{v.channel ?? "—"}</td>
                  <td>
                    <code className="path">{v.path}</code>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </section>
    </>
  );
}

function RulesSection({ format }: { format: Format }) {
  const [topic, setTopic] = useState<string>("all");
  const shown = topic === "all" ? format.rules : format.rules.filter((r) => r.topic === topic);
  const missing = format.topics.filter((t) => !t.path);

  return (
    <section className="format-section">
      <h2>Research rules that apply ({format.rules.length})</h2>
      <div className="chips">
        {["all", ...format.topics.filter((t) => t.path).map((t) => t.topic)].map((t) => (
          <button key={t} className={t === topic ? "active" : ""} onClick={() => setTopic(t)}>
            {t === "all" ? "All" : t}
          </button>
        ))}
      </div>
      {missing.length > 0 && (
        <p className="muted">No rules.md for topic {missing.map((t) => t.topic).join(", ")}.</p>
      )}
      {format.topics.length === 0 ? (
        <p className="muted">FORMAT.md names no topics under "Research rules that apply".</p>
      ) : (
        <table className="grid rules">
          <thead>
            <tr>
              <th>Id</th>
              <th>Rule</th>
              <th>Scope</th>
              <th>Tag</th>
              <th>Confidence</th>
              <th>Source</th>
            </tr>
          </thead>
          <tbody>
            {shown.map((r) => (
              <tr key={r.id}>
                <td>
                  <code>{r.id}</code>
                </td>
                <td>{r.rule}</td>
                <td>{r.scope}</td>
                <td>{r.tag}</td>
                <td>{r.confidence}</td>
                <td>
                  <Source rule={r} />
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
      <p className="muted">
        Edit the rules in{" "}
        {format.topics
          .filter((t) => t.path)
          .map((t, i) => (
            <span key={t.topic}>
              {i > 0 && ", "}
              <a href={DOC + encodeURIComponent(t.path as string)}>{t.path}</a>
            </span>
          ))}
      </p>
    </section>
  );
}

const LINK = /\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g;

function Source({ rule }: { rule: Rule }) {
  const parts: ReactNode[] = [];
  let last = 0;
  for (const m of rule.source.matchAll(LINK)) {
    parts.push(rule.source.slice(last, m.index));
    parts.push(
      <a key={m.index} href={m[2]} target="_blank" rel="noreferrer">
        {m[1]}
      </a>,
    );
    last = (m.index ?? 0) + m[0].length;
  }
  parts.push(rule.source.slice(last));
  return <>{parts}</>;
}
